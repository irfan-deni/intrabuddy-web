import { test, expect } from '@playwright/test'
import { setupPage } from './helpers'

test.beforeEach(async ({ page }) => {
  await page.setViewportSize({ width: 1469, height: 843 })
  await setupPage(page)
})

test('dashboard cards use shared radii without changing circular graphics', async ({ page }) => {
  await page.goto('/')
  await page.waitForLoadState('networkidle')
  const main = page.getByRole('main')
  const cards = main.locator('.rounded-card')
  await expect(cards).toHaveCount(7)
  for (const card of await cards.all()) await expect(card).toHaveCSS('border-radius', '12px')
  for (const button of await main.locator('header button').all()) await expect(button).toHaveCSS('border-radius', '8px')
  await expect(main.locator('.dashboard-placement-chart svg circle')).toHaveCount(2)
  await expect(main.locator('.rounded-full.h-4')).toHaveCSS('border-radius', '9999px')
  await expect(page.getByRole('complementary')).toHaveCSS('border-radius', '0px')
})

test('student table, badges and controls have rounded outer edges', async ({ page }) => {
  await page.goto('/students')
  await page.waitForLoadState('networkidle')
  const main = page.getByRole('main')
  const frame = main.locator('article')
  await expect(frame).toHaveCSS('border-radius', '12px')
  await expect(frame).toHaveCSS('overflow', 'hidden')
  await expect(page.getByRole('table')).toHaveCSS('border-radius', '0px')
  for (const control of await main.locator('header input[type="text"], header select, header button, tbody button').all()) {
    await expect(control).toHaveCSS('border-radius', '8px')
  }
  const badge = page.getByRole('cell', { name: 'Accepted', exact: true }).locator('span')
  await expect(badge).toHaveCSS('border-radius', '6px')
  await page.getByRole('table').locator('tbody tr').first().click()
  await expect(page).toHaveURL(/\/student\?id=/)
  const cards = page.getByRole('main').locator('.rounded-card')
  await expect(cards.first()).toBeVisible()
  for (const card of await cards.all()) await expect(card).toHaveCSS('border-radius', '12px')
})

test('rounded table preserves tablet scrolling and row-button focus clearance', async ({ page }) => {
  await page.setViewportSize({ width: 768, height: 843 })
  await page.goto('/students')
  await page.waitForLoadState('networkidle')
  const frame = page.getByRole('main').locator('article')
  const scroller = frame.locator('.overflow-x-auto')
  await expect(scroller).toHaveCSS('overflow-x', 'auto')
  expect(await scroller.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true)
  await scroller.evaluate(element => { element.scrollLeft = element.scrollWidth })
  const action = page.getByRole('table').locator('tbody tr').first().getByRole('button').last()
  await action.focus()
  await page.keyboard.press('Shift+Tab')
  await page.keyboard.press('Tab')
  await expect(action).toBeFocused()
  await expect(action).toHaveCSS('outline-style', 'solid')
  const actionBox = await action.boundingBox()
  const frameBox = await frame.boundingBox()
  expect(actionBox!.x).toBeGreaterThanOrEqual(frameBox!.x + 4)
  expect(actionBox!.x + actionBox!.width).toBeLessThanOrEqual(frameBox!.x + frameBox!.width - 4)
})

test('mobile cards and enrollment dialog retain rounding and usable scrolling', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 440 })
  await page.goto('/students')
  await page.waitForLoadState('networkidle')
  const card = page.locator('.app-surface-ui .md\\:hidden .rounded-card').first()
  await expect(card).toBeVisible()
  await expect(card).toHaveCSS('border-radius', '12px')
  await page.getByRole('button', { name: /Enroll Student/ }).click()
  const dialog = page.getByRole('heading', { name: 'Enroll Student', exact: true }).locator('..')
  await expect(dialog).toHaveCSS('border-radius', '16px')
  await expect(dialog).toHaveCSS('overflow-y', 'auto')
  expect(await dialog.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  for (const control of await dialog.locator('input, button').all()) await expect(control).toHaveCSS('border-radius', '8px')
  const submit = dialog.getByRole('button', { name: 'Confirm Enrollment', exact: true })
  await submit.scrollIntoViewIfNeeded()
  await expect(submit).toBeInViewport()
  await submit.focus()
  await page.keyboard.press('Shift+Tab')
  await page.keyboard.press('Tab')
  await expect(submit).toBeFocused()
  await expect(submit).toHaveCSS('outline-style', 'solid')
})
